/// Standard vector map style URLs provided free and open-source by OpenFreeMap.
class OpenFreeMapStyles {
  OpenFreeMapStyles._();

  /// Default bright / light street map style.
  static const String bright = 'https://tiles.openfreemap.org/styles/bright';

  /// High-contrast dark street map style for night driving and dark mode.
  static const String dark = 'https://tiles.openfreemap.org/styles/dark';

  /// OpenMapTiles Liberty style with detailed natural and urban features.
  static const String liberty = 'https://tiles.openfreemap.org/styles/liberty';

  /// Minimalist gray-scale style ideal for high-visibility data overlays.
  static const String positron = 'https://tiles.openfreemap.org/styles/positron';
}
